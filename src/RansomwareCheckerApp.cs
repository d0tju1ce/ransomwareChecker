    // The exe runs RansomwareChecker.ps1 elevated. Anyone who can write to the tool folder (share, USB stick, copy on a
    // compromised host) could swap the script or blind it with an empty indicators.json. SHA-256 of these files is
    // baked in at build time (Integrity.g.cs, generated by build.cmd); before a run the files are opened with
    // FileShare.Read - nobody can modify, rename or delete them until the script has finished - and compared.
    static partial class Integrity
    {
        public static List<FileStream> OpenAndVerify(string appDir, List<string> problems)
        {
            var handles = new List<FileStream>();
            for (int i = 0; i < Pinned.GetLength(0); i++)
            {
                string rel = Pinned[i, 0];
                FileStream fs;
                try { fs = new FileStream(Path.Combine(appDir, rel), FileMode.Open, FileAccess.Read, FileShare.Read); }
                catch (Exception ex) { problems.Add(rel + " - " + ex.Message); continue; }
                handles.Add(fs);
                string hex;
                using (var sha = SHA256.Create()) hex = BitConverter.ToString(sha.ComputeHash(fs)).Replace("-", "");
                if (!hex.Equals(Pinned[i, 1], StringComparison.OrdinalIgnoreCase)) problems.Add(rel + " - modified");
            }
            return handles;
        }
    }

