        // ---------- Running the script ----------

        static string PowerShellPath()
        {
            // 32-bit process on 64-bit Windows would get the redirected System32; use sysnative there
            string win = Environment.GetFolderPath(Environment.SpecialFolder.Windows);
            string sysDir = Environment.Is64BitOperatingSystem && !Environment.Is64BitProcess ? Path.Combine(win, "Sysnative") : Path.Combine(win, "System32");
            return Path.Combine(sysDir, @"WindowsPowerShell\v1.0\powershell.exe");
        }

        void StartRun()
        {
            if (running) return;
            if (!File.Exists(scriptPath))
            {
                runError = "RansomwareChecker.ps1 was not found next to the exe (" + appDir + ").";
                RefreshAll();
                return;
            }
            var problems = new List<string>();
            var handles = Integrity.OpenAndVerify(appDir, problems);
            if (problems.Count > 0 && MessageBox.Show(
                    "These files differ from the ones this exe was built and signed with:\r\n\r\n  " + string.Join("\r\n  ", problems.ToArray()) +
                    "\r\n\r\nThe script runs with administrator rights. Somebody with write access to " + appDir +
                    " could have replaced it or emptied the indicators.\r\nRun only if you changed the files yourself.\r\n\r\nRun the check anyway?",
                    App.Name + " - integrity check", MessageBoxButtons.YesNo, MessageBoxIcon.Warning, MessageBoxDefaultButton.Button2) != DialogResult.Yes)
            {
                foreach (var h in handles) h.Dispose();
                runError = "Check not started: " + problems[0] + (problems.Count > 1 ? " (+" + (problems.Count - 1) + " more)" : "") + ".";
                RefreshAll();
                return;
            }
            pinnedFiles = handles;
            running = true;
            cancelled = false;
            runError = null;
            checksDone = 0;
            checksTotal = quick ? 20 : 22;   // replaced by the "Checks: N" line of the script
            lastCheckLine = "";
            runStarted = DateTime.Now;
            RefreshAll();
            var t = new Thread(RunWorker) { IsBackground = true };
            t.Start();
        }

        void StopRun()
        {
            if (!running) return;
            if (MessageBox.Show("Stop the running check? No report will be produced.", App.Name, MessageBoxButtons.YesNo, MessageBoxIcon.Question) != DialogResult.Yes) return;
            cancelled = true;
            var p = proc;
            if (p != null) try { if (!p.HasExited) p.Kill(); } catch { }
        }

        void RunWorker()
        {
            string error = null;
            string folder = null, reportLine = null;
            var errText = new StringBuilder();
            try
            {
                string args = "-NoProfile -NonInteractive -ExecutionPolicy Bypass -File \"" + scriptPath + "\" -DaysBack " + daysBack
                              + (quick ? " -Quick" : "") + " -OutputPath \"" + reportsDir.TrimEnd('\\') + "\"";
                var psi = new ProcessStartInfo(PowerShellPath(), args)
                {
                    UseShellExecute = false, CreateNoWindow = true, WorkingDirectory = appDir,
                    RedirectStandardOutput = true, RedirectStandardError = true
                };
                using (var p = new Process { StartInfo = psi })
                {
                    p.OutputDataReceived += (s, e) =>
                    {
                        if (e.Data == null) return;
                        string line = e.Data.Trim();
                        int n;
                        if (line.StartsWith("Checks: ") && int.TryParse(line.Substring(8), out n) && n > 0) { checksTotal = n; return; }
                        if (line.StartsWith("Report: ")) { reportLine = line.Substring(8).Trim(); return; }
                        if (!line.StartsWith("[*]")) return;
                        checksDone++;
                        // "[*] Run / RunOnce keys      10 findings (High 0, Medium 0)  0.2s" -> "Run / RunOnce keys - 10 findings"
                        string name = line.Substring(3).Trim();
                        int cut = name.IndexOf("  ", StringComparison.Ordinal);
                        string rest = cut > 0 ? name.Substring(cut).Trim() : "";
                        if (cut > 0) name = name.Substring(0, cut);
                        int paren = rest.IndexOf(" (", StringComparison.Ordinal);
                        lastCheckLine = name + (rest.Length > 0 ? " - " + (paren > 0 ? rest.Substring(0, paren) : rest) : "");
                        try { BeginInvoke((Action)UpdateHero); } catch { }
                    };
                    p.ErrorDataReceived += (s, e) => { if (e.Data != null) lock (errText) errText.AppendLine(e.Data); };
                    p.Start();
                    proc = p;
                    p.BeginOutputReadLine();
                    p.BeginErrorReadLine();
                    p.WaitForExit();
                    proc = null;
                    if (cancelled) error = "The check was stopped.";
                    else
                    {
                        // The script prints "Report: <folder>"; only that folder (inside Reports) is accepted
                        string full = null;
                        try { if (reportLine != null) full = Path.GetFullPath(reportLine); } catch { }
                        if (full != null && full.StartsWith(Path.GetFullPath(reportsDir).TrimEnd('\\') + "\\", StringComparison.OrdinalIgnoreCase)
                            && File.Exists(Path.Combine(full, "findings.json"))) folder = full;
                        else
                        {
                            string err = errText.ToString().Trim();
                            error = "The script did not produce a report (exit code " + p.ExitCode + ")" + (err.Length > 0 ? ": " + FirstLine(err) : ".");
                            if (err.IndexOf("digitally signed", StringComparison.OrdinalIgnoreCase) >= 0 || err.IndexOf("PSSecurityException", StringComparison.OrdinalIgnoreCase) >= 0)
                                error += " Group Policy enforces an execution policy (AllSigned/RemoteSigned) that overrides -ExecutionPolicy Bypass:"
                                       + " import cert\\RansomwareChecker.cer into Trusted Publishers and Trusted Root, and unblock the downloaded files (Unblock-File).";
                        }
                    }
                }
            }
            catch (Exception ex) { error = "Cannot run PowerShell: " + ex.Message; }
            finally
            {
                var held = pinnedFiles;
                pinnedFiles = null;
                if (held != null) foreach (var h in held) h.Dispose();
            }

            Report loaded = null;
            if (folder != null)
            {
                try { loaded = Report.Load(folder); }
                catch (Exception ex) { error = "Cannot read the report: " + ex.Message; }
            }
            try
            {
                BeginInvoke((Action)delegate
                {
                    running = false;
                    runError = error;
                    if (loaded != null) { report = loaded; reportIsPrevious = false; }
                    RefreshAll();
                    if (loaded != null && !Focused && WindowState == FormWindowState.Minimized) FlashTitle();
                });
            }
            catch { }
        }

        static string FirstLine(string s)
        {
            int i = s.IndexOfAny(new[] { '\r', '\n' });
            return i > 0 ? s.Substring(0, i) : s;
        }

