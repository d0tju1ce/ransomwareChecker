# Writes Integrity.g.cs with the SHA-256 of the files the exe runs elevated (script + indicators + remediation).
# Called by build.cmd AFTER the script has been signed (the signature is part of the file) and before compiling.
# config\check_reasons.json is only displayed by the app, so it is not pinned and can be edited freely.
$root = Split-Path -Parent $PSScriptRoot
$files = 'RansomwareChecker.ps1', 'config\indicators.json', 'config\remediation.json'
$rows = foreach ($f in $files) {
    $hash = (Get-FileHash -LiteralPath (Join-Path $root $f) -Algorithm SHA256 -ErrorAction Stop).Hash
    '            {{ @"{0}", "{1}" }},' -f $f, $hash
}
$code = @"
// Generated by make_integrity.ps1 during build.cmd - do not edit.
namespace RansomwareChecker
{
    static partial class Integrity
    {
        static readonly string[,] Pinned =
        {
$($rows -join "`r`n")
        };
    }
}
"@
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'Integrity.g.cs'), $code, (New-Object Text.UTF8Encoding($false)))
$files | ForEach-Object { Write-Host "Pinned $_" }
